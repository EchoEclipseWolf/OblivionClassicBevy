/// IDA: the fourteen targets of 0044DCF0's switch.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConstructArm {
    /// 0044DE35.
    Tes4,
    /// 0044E326.
    Gmst,
    /// 0044E512.
    Skill,
    /// 0044E578: an existing form reloads; a new one is created, loaded and listed.
    List,
    /// 0044E5A5: type 0 and everything past 0x42 land here too.
    Default,
    /// 0044E367 MGEF, 0044DEF0 CELL, 0044E001 REFR/ACHR/ACRE, 0044E2A5 PGRD, 0044E401 WRLD, 0044E237 LAND, 0044DE83 ROAD, 0044E474 DIAL, 0044E4C9 INFO, 0044E556 IDLE: the class's `special_arm`.
    Special,
}

#[cfg(test)]
mod tests {
    use super::*;

    // The bytes at 0044E6DC and the 15 targets at 0044E6A0, as objdump shows them, mapped to the arms named above.
    #[test]
    fn construct_arm_is_the_exes_byte_table() {
        const BYTES: [u8; 0x43] = [
            0x00, 0x0E, 0x01, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x03, 0x04, 0x02, 0x02,
            0x02, 0x02, 0x02, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E,
            0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E,
            0x0E, 0x0E, 0x02, 0x02, 0x02, 0x05, 0x06, 0x06, 0x06, 0x07, 0x08, 0x09, 0x0E, 0x0A,
            0x0B, 0x0C, 0x02, 0x0D, 0x02, 0x02, 0x02, 0x0E, 0x02, 0x02, 0x02,
        ];
        let arm = |target: u8| match target {
            0x00 => ConstructArm::Tes4,
            0x01 => ConstructArm::Gmst,
            0x02 => ConstructArm::List,
            0x03 => ConstructArm::Skill,
            0x0E => ConstructArm::Default,
            _ => ConstructArm::Special,
        };
        for (index, target) in BYTES.iter().enumerate() {
            assert_eq!(
                construct_arm(index as u32 + 1),
                arm(*target),
                "type {:02X}",
                index + 1
            );
        }
        assert_eq!(
            construct_arm(0),
            ConstructArm::Default,
            "`lea eax, [ebx-1]` wraps"
        );
        assert_eq!(construct_arm(0x44), ConstructArm::Default);
    }
}
