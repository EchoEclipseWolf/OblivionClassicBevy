/// IDA: 00403CF0 Input_ScanCodeToCharacter(scan, shift) (`retn 8`): past 0xFF -1; else the table byte for the layout
/// (00B02C44 iLanguage:Controls: 1 German, 2 French, 3 Spanish, 4 Italian, anything else US), shifted or plain,
/// zero-extended. Completion: 100%.
#[must_use]
pub fn scan_code_to_character(scan: u32, shift: bool, layout: u32) -> i32 {
    if scan > 0xFF {
        return -1;
    }
    let table = match (layout, shift) {
        (1, false) => &SCAN_CODE_CHARS_GERMAN_PLAIN,
        (1, true) => &SCAN_CODE_CHARS_GERMAN_SHIFTED,
        (2, false) => &SCAN_CODE_CHARS_FRENCH_PLAIN,
        (2, true) => &SCAN_CODE_CHARS_FRENCH_SHIFTED,
        (3, false) => &SCAN_CODE_CHARS_SPANISH_PLAIN,
        (3, true) => &SCAN_CODE_CHARS_SPANISH_SHIFTED,
        (4, false) => &SCAN_CODE_CHARS_ITALIAN_PLAIN,
        (4, true) => &SCAN_CODE_CHARS_ITALIAN_SHIFTED,
        (_, false) => &SCAN_CODE_CHARS_US_PLAIN,
        (_, true) => &SCAN_CODE_CHARS_US_SHIFTED,
    };
    i32::from(table[scan as usize])
}

/// IDA: 0057F7A0 InterfaceManager_TranslateKeyEventAndUpdateModifiers(event, scan) for a press (event 1): the character
/// by 00403CF0 with the manager's shift byte; Escape (27) and '|' (124) give 0; Backspace (8) gives 0x80000000 and
/// clears the repeat (+0x120 = `ticks`, +0x124 = 0, +0x11C = 0x80000000); Enter (13) 0x80000008; then by scan code: the
/// shifts set +0x10C bit 4 and the translation shift, the alts bit 1, the controls bit 2 (each 0); Left and Right start
/// their repeat (0057DC30) and give 0x80000001 / 0x80000002, Up 0x80000003, Down 0x80000004, Home 0x80000005, End
/// 0x80000006, PageDown 0x8000000A, PageUp 0x80000009, Delete (repeat started) 0x80000007; else the character. A
/// release (event 2) clears the shift, alt or control and the repeat and gives 0. Completion: 100%; the repeat itself
/// (0057DC60, which reads these fields each frame) isn't ported.
pub fn translate_key_event(
    manager: &mut InterfaceManager,
    pressed: bool,
    scan: u32,
    layout: u32,
    ticks: u32,
) -> i32 {
    if !pressed {
        match scan {
            0x2A | 0x36 => {
                manager.input_modifier_flags &= 0xFFFB;
                manager.shift_down_for_key_translation = false;
            }
            0x38 | 0xB8 => manager.input_modifier_flags &= 0xFFFE,
            0x1D | 0x9D => manager.input_modifier_flags &= 0xFFFD,
            _ => {}
        }
        start_key_repeat(manager, 0, ticks);
        return 0;
    }
    let character = scan_code_to_character(scan, manager.shift_down_for_key_translation, layout);
    match character {
        27 | 124 => return 0,
        8 => {
            start_key_repeat(manager, 0x8000_0000, ticks);
            return KEY_BACKSPACE;
        }
        13 => return super::interface_frame::KEY_ENTER,
        _ => {}
    }
    match scan {
        0x2A | 0x36 => {
            manager.input_modifier_flags |= 4;
            manager.shift_down_for_key_translation = true;
            0
        }
        0x38 | 0xB8 => {
            manager.input_modifier_flags |= 1;
            0
        }
        0x1D | 0x9D => {
            manager.input_modifier_flags |= 2;
            0
        }
        0xCB => {
            start_key_repeat(manager, super::interface_frame::KEY_LEFT as u32, ticks);
            super::interface_frame::KEY_LEFT
        }
        0xCD => {
            start_key_repeat(manager, super::interface_frame::KEY_RIGHT as u32, ticks);
            super::interface_frame::KEY_RIGHT
        }
        0xC8 => super::interface_frame::KEY_UP,
        0xD0 => super::interface_frame::KEY_DOWN,
        0xC7 => KEY_HOME,
        0xCF => KEY_END,
        0xD1 => KEY_PAGE_DOWN,
        0xC9 => KEY_PAGE_UP,
        0xD3 => {
            start_key_repeat(manager, KEY_DELETE as u32, ticks);
            KEY_DELETE
        }
        _ => character,
    }
}

/// IDA: 0057DC30 InterfaceManager_StartNavigationKeyRepeat(key): +0x120 = g_timeInfo +0x10, +0x124 = 0, +0x11C = key.
/// Completion: 100%.
fn start_key_repeat(manager: &mut InterfaceManager, key: u32, ticks: u32) {
    manager.key_pressed_tick_120 = ticks;
    manager.last_key_repeat_tick_124 = 0;
    manager.pending_repeat_key_11c = key;
}

#[cfg(test)]
mod tests {
    use super::*;

    // The US tables: 'a' (0x1E), shifted 'A', '1' (0x02) and '!', Space (0x39), Backspace 8, Enter 13.
    #[test]
    fn the_us_tables_give_characters() {
        assert_eq!(scan_code_to_character(0x1E, false, 0), i32::from(b'a'));
        assert_eq!(scan_code_to_character(0x1E, true, 0), i32::from(b'A'));
        assert_eq!(scan_code_to_character(0x02, false, 0), i32::from(b'1'));
        assert_eq!(scan_code_to_character(0x02, true, 0), i32::from(b'!'));
        assert_eq!(scan_code_to_character(0x39, false, 0), i32::from(b' '));
        assert_eq!(scan_code_to_character(0x0E, false, 0), 8);
        assert_eq!(scan_code_to_character(0x1C, false, 0), 13);
        assert_eq!(scan_code_to_character(0x100, false, 0), -1);
    }
}
