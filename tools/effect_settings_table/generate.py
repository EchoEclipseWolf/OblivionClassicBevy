#!/usr/bin/env python3
"""Generate tes/forms/effect_settings_table.rs from the C++ table, which came from evidence/phase12-window-2026-10-09/effects-builtin.tsv in IDA, and check every row against the push arguments of the 00417220 calls in 00417420, read with objdump from the evidence binary."""
import re
import subprocess

SRC = '/run/media/natfoth/Echo/OblivionRecomp/src/tes/effect_settings_table.inc'
OUT = 'crates/oblivion_sim/src/tes/forms/effect_settings_table.rs'
EXE = '/run/media/natfoth/Echo/OblivionBot/Oblivion.exe'
ROW = re.compile(r'^\{(0x[0-9A-F]+)U, (0x[0-9A-F]+)U, ("(?:[^"\\]|\\.)*"), (0x[0-9A-F]+)U, (0x[0-9A-F]+)U, (0x[0-9A-F]+)U, (0x[0-9A-F]+)U, (0x[0-9A-F]+)U, (\d+), \{([^}]*)\}\},$')

rows = []
for line in open(SRC, encoding='ascii'):
    if line.startswith('{'):
        m = ROW.match(line.rstrip())
        if not m:
            raise SystemExit('unparsed row: ' + line)
        call, code, name, school, cost, associated, flags, resist, count, counters = m.groups()
        codes = [c.strip().rstrip('U') for c in counters.split(',') if c.strip()]
        rows.append((int(call, 16), int(code, 16), name, int(school, 16), int(cost, 16), int(associated, 16), int(flags, 16), int(resist, 16), int(count), [int(c, 16) for c in codes]))
assert len(rows) == 161, len(rows)
assert len({row[1] for row in rows}) == 161, 'a repeated code would replace a map entry'

# The exe: pushes since the last call, right to left, at each `call 0x417220`.
disassembly = subprocess.run(['objdump', '-d', '-M', 'intel', '--no-show-raw-insn', '--start-address=0x417420', '--stop-address=0x418db0', EXE], capture_output=True, text=True, check=True).stdout
data = open(EXE, 'rb').read()
def file_offset(va):
    pe = int.from_bytes(data[0x3c:0x40], 'little')
    count = int.from_bytes(data[pe + 6:pe + 8], 'little')
    optional = int.from_bytes(data[pe + 20:pe + 22], 'little')
    for index in range(count):
        at = pe + 24 + optional + 40 * index
        size, rva, raw_size, raw = (int.from_bytes(data[at + 8 + 4 * k:at + 12 + 4 * k], 'little') for k in range(4))
        if rva <= va - 0x400000 < rva + raw_size:
            return raw + va - 0x400000 - rva
    raise SystemExit(f'no section for {va:x}')
def string_at(va):
    start = file_offset(va)
    return data[start:data.index(b'\0', start)].decode('ascii')
pushes = []
checked = 0
st0 = None
extra_pushes = []
for line in disassembly.splitlines():
    m = re.match(r'\s+([0-9a-f]+):\s+(\S+)\s*(.*)', line)
    if not m:
        continue
    address, op, operand = int(m.group(1), 16), m.group(2), m.group(3).strip()
    if op == 'fldz':
        st0 = 0
    elif op == 'fld1':
        st0 = 0x3F800000
    elif op == 'fld':
        at = re.search(r'ds:0x([0-9a-f]+)', operand)
        assert at, line
        st0 = int.from_bytes(data[file_offset(int(at.group(1), 16)):][:4], 'little')
    elif op == 'push':
        # `push ecx`, then `fstp [esp]`: the cost, a float argument.
        pushes.append(hex(st0) if operand == 'ecx' else operand)
    elif op == 'call':
        if operand == '0x417220':
            row = rows[checked]
            assert row[0] == address, f'row {checked}: call {row[0]:x}, exe {address:x}'
            args = pushes[::-1]
            values = [int(a, 16) if a.startswith('0x') else (int(a) if a.isdigit() else None) for a in args]
            assert None not in values, f'{address:x}: a push that is not a constant: {args}'
            # (code, name, school, cost, associated, flags, resist, count, counters...)
            want = [row[1], None, row[3], row[4], row[5], row[6], row[7], row[8]] + row[9]
            # A push past the count is an argument 00415D40 never reads ('DUMY' at 00417FF0).
            assert len(values) >= len(want), f'{address:x}: {len(values)} pushes, {len(want)} in the row: {args}'
            if len(values) > len(want):
                extra_pushes.append((address, values[len(want):]))
            for index, (have, expected) in enumerate(zip(values, want)):
                if index != 1:
                    assert have == expected, f'{address:x} argument {index}: exe {have:#x}, table {expected:#x}'
            assert string_at(values[1]) == row[2].strip('"'), f'{address:x}: name {string_at(values[1])!r}, table {row[2]}'
            checked += 1
        pushes = []
    elif op in ('add', 'sub') and operand.startswith('esp'):
        pass
assert checked == 161, checked

out = [
    '//! IDA: the 161 00417220 EffectSettingCollection_RegisterEffect calls of 00417420, in call order. Generated by tools/effect_settings_table/generate.py from the C++ table, which checks each row against the exe\'s pushes. Do not edit.',
    '',
    'use super::forms_magic::BuiltInEffect;',
    '',
    '#[allow(clippy::too_many_arguments, reason = "one row of 00417220\'s arguments")]',
    'const fn e(call: u32, code: u32, name: &\'static [u8], school: u32, cost_bits: u32, associated: u32, flags: u32, resist: u32, counters: &\'static [u32]) -> BuiltInEffect {',
    '    BuiltInEffect { call, code, name, school, cost_bits, associated, flags, resist, counters }',
    '}',
    '',
    '#[rustfmt::skip]',
    'pub const BUILT_IN_EFFECTS: [BuiltInEffect; 161] = [',
]
for call, code, name, school, cost, associated, flags, resist, count, counters in rows:
    assert count == len(counters)
    listed = ', '.join(f'0x{c:08X}' for c in counters)
    out.append(f'    e(0x{call:08X}, 0x{code:08X}, b{name}, 0x{school:X}, 0x{cost:08X}, 0x{associated:X}, 0x{flags:08X}, 0x{resist:X}, &[{listed}]),')
out += ['];', '']
open(OUT, 'w', encoding='ascii').write('\n'.join(out))
print(f'{checked} rows, each checked against the exe; pushes past the count: ' + ', '.join(f'{a:08X}: {[hex(v) for v in e]}' for a, e in extra_pushes))
