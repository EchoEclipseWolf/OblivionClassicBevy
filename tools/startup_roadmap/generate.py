"""Generate inert Rust startup metadata, and at cutover the call/CFG ledger, from saved IDA evidence.

Usage: python3 tools/startup_roadmap/generate.py
No original address is callable. Only one repository may write Startup-Call-Ledger.md. Until the cutover that is the
C++ one, so this writes the ledger only when given --notes-at-cutover.
"""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
data = json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))
status = json.loads((HERE / "dispositions.json").read_text(encoding="utf-8"))
functions = {f["entry"]: f for f in data["functions"]}


def disposition(kind, identity, default="pending"):
    return status.get(kind, {}).get(hx(identity), default)


def resolution_for(kind, indirect):
    if kind == "obsolete_runtime":
        return "obsolete_runtime"
    if kind == "host_supplied":
        return "host_supplied"
    if kind == "implemented_behavior":
        return "implemented_local"
    return "unresolved_indirect" if indirect else "pending_body"


def hx(value):
    return f"{value:08X}"


def lit(value):
    text = json.dumps(value or "", ensure_ascii=True)
    # JSON's \\uXXXX is not a Rust escape.
    return re.sub(r"\\\\u([0-9a-fA-F]{4})", r"\\\\u{\\1}", text)


def name_for(identity, fallback):
    return status.get("name_overrides", {}).get(hx(identity), fallback)


def signature_for(identity, default="Unrecovered original signature"):
    return (status.get("signature_overrides", {}).get(hx(identity)) or
            functions.get(identity, {}).get("signature") or
            default)


def stub_name(identity):
    kind = disposition("dependencies", identity)
    prefix = "implemented" if kind == "implemented_behavior" else "pending"
    return f"{prefix}_{hx(identity)}"


def md(value):
    return str(value or "Unknown").replace("|", "&#124;").replace("\n", " ")


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(value, encoding="utf-8")
    temporary.replace(path)


ordered = []


def visit(entry):
    if entry in ordered or entry not in functions:
        return
    ordered.append(entry)
    f = functions[entry]
    for call in f["calls"]:
        visit(call["target"])
    for block in f["blocks"]:
        for successor in block["successors"]:
            if successor != entry:
                visit(successor)


visit(data["root"])
for entry in functions:
    visit(entry)

# Every direct target and unresolved callsite gets a concrete, address-stable stub.
# Captured owners also have stubs, including zero-call bodies and external tails.
deps = {}
for entry in ordered:
    f = functions[entry]
    deps.setdefault(entry, (name_for(entry, f["name"]), False))
    for call in f["calls"]:
        identity = call["target"] or call["site"]
        deps.setdefault(identity, (name_for(identity, call["name"] or call["operand"]), call["target"] is None))
    local = {b["start"] for b in f["blocks"] if b["start"] < b["end"]}
    for block in f["blocks"]:
        for successor in block["successors"]:
            if successor not in local:
                deps.setdefault(successor, (functions.get(successor, {}).get("name", f"tail_{hx(successor)}"), False))

valid_dispositions = {"pending", "unresolved", "obsolete_runtime", "host_supplied", "implemented_behavior"}
known_sites = {c["site"] for f in functions.values() for c in f["calls"]}
for category, known in (("dependencies", deps), ("callsites", known_sites)):
    for key, kind in status.get(category, {}).items():
        if int(key, 16) not in known or kind not in valid_dispositions:
            raise ValueError(f"Unknown {category} disposition: {key}={kind}")
for key in status.get("signature_overrides", {}):
    if int(key, 16) not in deps:
        raise ValueError(f"Unknown signature override: {key}")
for key, item in status.get("reviewed_frontier", {}).items():
    if int(key, 16) in deps:
        raise ValueError(f"Move captured frontier symbol to ordinary overrides: {key}")
    if item.get("status") not in {"pending", "host_supplied"} or not all(
            item.get(field) for field in ("name", "signature", "evidence")):
        raise ValueError(f"Incomplete reviewed frontier evidence: {key}")
    if item["status"] == "host_supplied" and not item.get("host_reason"):
        raise ValueError(f"Missing host-service justification: {key}")

rust = ['// Generated by tools/startup_roadmap/generate.py; edit manifest/generator, not this file.',
        '// Dispositions are the C++ port\'s record; see the note on `crate::scaffold`.',
        'use crate::scaffold::{',
        '    BasicBlock, CallSite, Dependency, FunctionPlan, PendingCall, Resolution as R, ScopeDisposition as D,',
        '};', '']
RESOLUTION = {"pending_body": "PendingBody", "unresolved_indirect": "UnresolvedIndirect",
              "implemented_local": "ImplementedLocal", "obsolete_runtime": "ObsoleteRuntime",
              "host_supplied": "HostSupplied"}
DISPOSITION = {"pending": "Pending", "unresolved": "Unresolved", "obsolete_runtime": "ObsoleteRuntime",
               "host_supplied": "HostSupplied", "implemented_behavior": "ImplementedBehavior"}


def stub(identity):
    indirect = deps[identity][1]
    kind = disposition("dependencies", identity, "unresolved" if indirect else "pending")
    return f'PendingCall {{ identity: 0x{hx(identity)}, resolution: R::{RESOLUTION[resolution_for(kind, indirect)]} }}'


rust += ['#[rustfmt::skip]', 'pub static DEPENDENCIES: &[Dependency] = &[']
for identity, (name, indirect) in deps.items():
    sig = signature_for(identity)
    kind = disposition("dependencies", identity, "unresolved" if indirect else "pending")
    rust += [f'    Dependency {{ identity: 0x{hx(identity)}, name: {lit(name)}, original_signature: {lit(sig)}, '
             f'body_captured: {str(identity in functions).lower()}, disposition: D::{DISPOSITION[kind]}, stub: {stub(identity)} }},']
rust += ['];', '']
rust += ['#[rustfmt::skip]', 'pub static FUNCTIONS: &[FunctionPlan] = &[']
for entry in ordered:
    f = functions[entry]
    rust += [f'    FunctionPlan {{ entry: 0x{hx(entry)}, name: {lit(f["name"])}, calls: &[']
    for c in f['calls']:
        identity = c['target'] or c['site']
        kind = disposition("callsites", c["site"], "unresolved" if c["target"] is None else "pending")
        rust += [f'        CallSite {{ site: 0x{hx(c["site"])}, target: 0x{hx(c["target"] or 0)}, pointer_slot: 0x{hx(c["pointer_slot"] or 0)}, '
                 f'instruction: {lit(c["assembly"])}, disposition: D::{DISPOSITION[kind]}, stub: {stub(identity)} }},']
    rust += ['    ], blocks: &[']
    for b in f['blocks']:
        successors = ', '.join(f'0x{hx(s)}' for s in b['successors'])
        rust += [f'        BasicBlock {{ start: 0x{hx(b["start"])}, end: 0x{hx(b["end"])}, tail_instruction: {lit(b["tail"])}, successors: &[{successors}] }},']
    rust += ['    ] },']
rust += ['];', '']
write(ROOT / 'crates/oblivion_testkit/src/scaffold_data.rs', '\n'.join(rust))

parser = argparse.ArgumentParser()
parser.add_argument('--notes-at-cutover', dest='notes', type=Path)
args = parser.parse_args()
calls = sum(len(f['calls']) for f in functions.values())
indirects = sum(c['target'] is None for f in functions.values() for c in f['calls'])
blocks = sum(len(f['blocks']) for f in functions.values())
lines = ['# Startup call-by-call ledger', '',
         'Generated from the preserved 2026-09-24 IDA capture; [roadmap](Startup-Roadmap.md).', '',
         '**`implemented_behavior` here records the C++ port**, from `dispositions.json`, frozen at `cpp-frozen-2026-11-06`. '
         'What the Rust port has is `RUST_PORTED_THROUGH` in `crates/oblivion_testkit/src/scaffold.rs`.', '',
         f'{len(functions)} captured bodies; {calls} call sites; {blocks} CFG blocks (including external tail nodes); '
         f'{indirects} raw indirect call sites; {len(deps)} defined dependency methods.', '',
         '**Read order:** begin at `0098787C`; follow each basic block and its successor edges. '
         'Call rows are ordered by instruction address inside each function, not a claim that every branch runs. '
         'Enter the linked callee at that callsite and return before advancing the caller. Loops may repeat rows. '
         'A conditional jump preserves the branch instruction and both successors, but its semantic predicate remains TODO. '
         'Zero-width blocks are external tail destinations. Indirect targets and uncaptured bodies stop the known expansion; '
         'pending TODO stubs never report completion. Explicit obsolete/host-supplied '
         'dispositions are completed scope decisions; implemented_local marks a bounded host '
         'body with transitive work still pending. Neither finishes game loading jobs.', '',
         'WinMain `0040F0E5` is an idle-loop announcement log, not a proven handoff. The capture retains '
         'the first message pump at `0040F13D..0040F164` and stops at the uncaptured continuation '
         '`0040F16A`. The normal MainMenu/title path and alternate movie-wait path are both present. '
         'The discontiguous `0040F62C` WinMain security-cookie return tail is host-CRT-owned. '
         'CRT return/exception cleanup and other menu-factory cases remain conditional context. '
         'Later gameplay, save loading and shutdown are separate milestones. This is not a complete transitive engine call graph.', '',
         'All addresses below are evidence IDs only. Source: `tools/startup_roadmap/manifest.json`; '
         'code: `crates/oblivion_testkit/src/scaffold_data.rs`; dispositions: '
         '`tools/startup_roadmap/dispositions.json`. Every dependency carries a stub record '
         'with its identity and resolution. Original signatures '
         'are metadata, never a callable cast.', '',
         '## Captured body index', '', '| Entry | Function | Calls | Blocks | Scaffold behavior |',
         '|---|---|---:|---:|---|']
for entry in ordered:
    f = functions[entry]
    kind = disposition("dependencies", entry)
    lines += [f'| [{hx(entry)}](#function-{hx(entry).lower()}) | `{md(f["name"])}` | {len(f["calls"])} | {len(f["blocks"])} | {kind} |']
for entry in ordered:
    f = functions[entry]
    kind = disposition("dependencies", entry)
    lines += ['', f'<a id="function-{hx(entry).lower()}"></a>', f'## {hx(entry)} — {f["name"]}', '',
              f'Original signature: `{md(f["signature"])}`. Unknown signatures remain TODO; host methods do not establish original ABI.', '',
              '- [x] Preserve direct call sites and basic-block successor graph.']
    if kind in ("obsolete_runtime", "host_supplied"):
        lines += [f'- [x] {kind}: completed scope decision; see the startup implementation report.',
                  '- [ ] Audit game-specific callbacks or callees separately where present.']
    else:
        lines += ['- [ ] Recover predicates, arguments, globals, side effects and indirect/tail targets.',
                  '- [ ] Implement original behavior or document an explicit host substitution.',
                  '- [ ] Validate normal, alternate, cancellation and failure paths before wiring this body.']
    lines += ['',
              '| Call site / stable ID | Owning block | Original target / instruction | Dependency body | Implementation |',
              '|---|---|---|---|---|']
    for c in f['calls']:
        owner = next((b['start'] for b in f['blocks'] if b['start'] <= c['site'] < b['end']), None)
        assert owner is not None, c
        identity = c['target'] or c['site']
        target = f'`{hx(c["target"])} {md(name_for(c["target"], c["name"]))}`' if c['target'] else f'**Unresolved** `{md(c["operand"])}`'
        link = (f'[captured](#function-{hx(identity).lower()})' if identity in functions else
                f'[local body](#dependency-{hx(identity).lower()})' if
                disposition("dependencies", identity) == "implemented_behavior" else
                f'[TODO](#dependency-{hx(identity).lower()})')
        kind = disposition("callsites", c["site"], "unresolved" if c["target"] is None else "pending")
        lines += [f'| C-{hx(c["site"])} | `{hx(owner)}` | {target}; `{md(c["assembly"])}` | {link} | {kind} |']
    lines += ['', '| Block [start, end) | Tail instruction | Successors (branch/loop/tail order) |', '|---|---|---|']
    for b in f['blocks']:
        successors = ', '.join(f'`{hx(s)}`' for s in b['successors']) or 'Return / no captured successor'
        lines += [f'| `{hx(b["start"])}..{hx(b["end"])}` | `{md(b["tail"])}` | {successors} |']
lines += ['', '## Dependency implementation frontier', '',
          '`0%*` means the original body has not been implemented/audited in this scaffold. '
          'It is not a new score for IDA understanding or existing host equivalents. '
          'A captured body only establishes the bounded instruction inventory, not recursive completeness.', '',
          '| Address / callsite | Name | Captured body | Original execution in scaffold | Remaining checklist |',
          '|---|---|---|---|---|']
for identity, (name, indirect) in deps.items():
    kind = disposition("dependencies", identity, "unresolved" if indirect else "pending")
    remaining = ('[ ] Recover; [ ] implement; [ ] test' if kind in ("pending", "unresolved") else
                 '[x] Local body; [ ] transitive effects; [ ] external validation' if
                 kind == "implemented_behavior" else
                 'Completed scope decision; game callbacks tracked separately')
    lines += [f'| <a id="dependency-{hx(identity).lower()}"></a>`{hx(identity)}` {"(indirect site)" if indirect else ""} | `{md(name)}` | {"Yes" if identity in functions else "No"} | {kind} | {remaining} |']
lines += ['', '## Maintenance', '',
          '- Add new captured bodies to the manifest from preserved evidence; never invent a callee or predicate.',
          '- Re-run the generator and formatter. Preserve stable address IDs and recorded source hashes.',
          '- Update the roadmap and per-function progress reports when implementing a stub; the generator must stop emitting a pending body for implemented methods.',
          '- Keep existing host equivalents separately scored until the original contract and ownership are satisfied.',
          '- Use the established 100% translation + 10% external validation scale in function reports; compilation alone earns no validation bonus.', '']
if status.get("callback_frontier"):
    lines += ['', '## Dynamic callback frontier', '',
              'The CRT scheduler is host-owned. Game-specific CRT and WinMain callbacks remain independent pending work.', '',
              '| Owner | Indirect call | Table | Status and evidence |', '|---|---|---|---|']
    for item in status["callback_frontier"]:
        lines += [f'| `{item["owner"]}` | `{item["site"]}` | `{item["table_start"]}..{item["table_end_exclusive"]}` | {md(item["status"])}: {md(item["evidence"])} |']
if status.get("reviewed_frontier"):
    lines += ['', '## Reviewed symbols beyond the captured graph', '',
              'These symbols were reached by later analysis. They retain verified names and '
              'signatures without inventing captured bodies, callsites or executable host stubs. '
              'Each row states its reviewed scope; these rows do not change the capture counts above.', '',
              '| Address | Name | Original signature | Status and evidence |',
              '|---|---|---|---|']
    for key, item in status["reviewed_frontier"].items():
        lines += [f'| `{key}` | `{md(item["name"])}` | `{md(item["signature"])}` | '
                  f'{md(item["status"])}: {md(item["evidence"])} '
                  f'{md(item.get("host_reason", ""))} |']
if args.notes:
    write(args.notes / 'Startup-Call-Ledger.md', '\n'.join(lines))
summary = {'bodies': len(functions), 'calls': calls, 'blocks': blocks, 'indirect_calls': indirects,
           'dependencies': len(deps), 'uncaptured_dependencies': sum(e not in functions for e in deps)}
write(HERE / 'summary.json', json.dumps(summary, indent=2) + '\n')
print(json.dumps(summary))
