#!/usr/bin/env python3
"""Generate tes/interface/menu_slots_table.rs from menu_vtables.json, which IDA read from the menu classes' vtables (2026-11-08).

Each class row holds its 15 vtable slots (`Menu_vtbl`: +0x00 .. +0x38) and its GetID value. A slot equal to the base
`Menu` vtable's is the base's function. Run from the repository root.
"""
import json

SRC = 'tools/menu_slots_table/menu_vtables.json'
OUT = 'crates/oblivion_sim/src/tes/interface/menu_slots_table.rs'

data = json.load(open(SRC, encoding='ascii'))
names = data['slot_names']
base = data['base']
assert len(names) == 15 and len(base['slots']) == 15
classes = sorted(data['classes'].items(), key=lambda item: item[1]['menu_id'])
assert len(classes) == 46, len(classes)


def slots(row):
    return ', '.join('0x' + slot for slot in row)


out = [
    "//! IDA: the menu classes' vtables (`Menu_vtbl`, 15 slots: +0x00 .. +0x38) and their GetID values, read from the exe's",
    "//! `??_7<class>@@6B@` tables. Generated by tools/menu_slots_table/generate.py from menu_vtables.json. Do not edit.",
    '',
    'use super::menu_slots::MenuSlotRow;',
    '',
    f"/// IDA: {base['vtable']} the base `Menu` vtable: a class slot equal to this one is the base's function.",
    '#[rustfmt::skip]',
    f"pub const BASE_MENU_SLOTS: [u32; 15] = [{slots(base['slots'])}];",
    '',
    '#[rustfmt::skip]',
    'pub const MENU_SLOT_ROWS: &[MenuSlotRow] = &[',
]
for name, row in classes:
    out.append(
        f"    MenuSlotRow {{ id: {row['menu_id']}, class: \"{name}\", vtable: 0x{row['vtable']}, "
        f"slots: [{slots(row['slots'])}] }},"
    )
out += ['];', '']
open(OUT, 'w', encoding='ascii').write('\n'.join(out))
