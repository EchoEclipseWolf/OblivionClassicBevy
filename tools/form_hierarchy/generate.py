#!/usr/bin/env python3
"""Generate crates/oblivion_sim/src/tes/forms/form_hierarchy.rs: which RTTI classes each form type casts to.

Read from the evidence binary: each class's vtable -> complete object locator (vtable - 4) -> class hierarchy
descriptor -> base class array -> type descriptors. A class that appears twice in the array is ambiguous, and
__RTDynamicCast gives null for it, so it is left out (the rule 00466E80 relies on). Run from the repository root.
"""
import re
import struct

EXE = '/run/media/natfoth/Echo/OblivionBot/Oblivion.exe'
MAP = 'crates/oblivion_sim/src/tes/forms/form_type_map.rs'
OUT = 'crates/oblivion_sim/src/tes/forms/form_hierarchy.rs'

data = open(EXE, 'rb').read()
pe = struct.unpack_from('<I', data, 0x3C)[0]
sections = struct.unpack_from('<H', data, pe + 6)[0]
optional = struct.unpack_from('<H', data, pe + 20)[0]
base = struct.unpack_from('<I', data, pe + 52)[0]
table = []
for index in range(sections):
    at = pe + 24 + optional + 40 * index
    virtual_size, virtual_address, raw_size, raw_offset = struct.unpack_from('<IIII', data, at + 8)
    table.append((virtual_address + base, max(virtual_size, raw_size), raw_offset))


def offset(va):
    for start, size, raw in table:
        if start <= va < start + size:
            return raw + va - start
    raise ValueError(hex(va))


def dword(va):
    return struct.unpack_from('<I', data, offset(va))[0]


def type_name(descriptor):
    at = offset(descriptor + 8)
    end = data.index(b'\0', at)
    return data[at:end].decode('ascii')


def bases(vtable):
    locator = dword(vtable - 4)
    hierarchy = dword(locator + 0x10)
    count = dword(hierarchy + 8)
    array = dword(hierarchy + 12)
    names = [type_name(dword(dword(array + 4 * index))) for index in range(count)]
    return [name for name in names if names.count(name) == 1]


def clean(name):
    match = re.fullmatch(r'\.\?AV(\w+)@@', name)
    return match.group(1) if match else None


source = open(MAP, encoding='ascii').read()
rows = re.findall(r'form_type: 0x([0-9A-F]+),\s*name: "(\w+)",\s*size: 0x[0-9A-F]+,\s*constructor: 0x[0-9A-F]+,\s*vtable: 0x([0-9A-F]+),', source)
classes = {}
names = {}
for form_type, name, vtable in rows:
    classes[int(form_type, 16)] = bases(int(vtable, 16))
    names[int(form_type, 16)] = name
extra_vtables = {}
for path, pattern, form_type, name in [
    ('crates/oblivion_sim/src/tes/forms/forms_dialogue.rs', r'TOPIC_VTABLES?: [^=]*= (?:\[)?\s*0x([0-9A-F_]+)', 0x39, 'DIAL'),
    ('crates/oblivion_sim/src/tes/forms/forms_dialogue.rs', r'INFO_VTABLES?: [^=]*= (?:\[)?\s*0x([0-9A-F_]+)', 0x3A, 'INFO'),
    ('crates/oblivion_sim/src/tes/actors/actor.rs', r'CHARACTER_VTABLES?: [^=]*= (?:\[)?\s*0x([0-9A-F_]+)', 0x32, 'ACHR'),
    ('crates/oblivion_sim/src/tes/actors/actor.rs', r'CREATURE_VTABLES?: [^=]*= (?:\[)?\s*0x([0-9A-F_]+)', 0x33, 'ACRE'),
]:
    text = open(path, encoding='utf-8').read()
    match = re.search(pattern, text)
    if not match:
        raise SystemExit(f'no vtable for {name} in {path}')
    classes[form_type] = bases(int(match.group(1).replace('_', ''), 16))
    names[form_type] = name

used = sorted({clean(name) for row in classes.values() for name in row if clean(name)})
lines = [
    '//! IDA: each form type\'s RTTI bases, read from the vtable -> complete object locator -> class hierarchy descriptor -> base class array of the evidence binary, as `__RTDynamicCast(form, 0, TESForm, X, 0)` answers them. A class twice in a hierarchy is ambiguous and left out. Generated by tools/form_hierarchy/generate.py. Do not edit.',
    '',
    '#[allow(non_camel_case_types)]',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub enum RttiClass {',
]
lines += [f'    {name},' for name in used]
lines += ['}', '', '/// IDA: `__RTDynamicCast` of a form of this type to `class`: true when it answers non-null.', '#[must_use]', '#[rustfmt::skip]', 'pub const fn form_type_casts_to(form_type: u8, class: RttiClass) -> bool {', '    match form_type {']
for form_type in sorted(classes):
    members = ' | '.join(f'RttiClass::{clean(name)}' for name in classes[form_type] if clean(name))
    lines.append(f'        0x{form_type:02X} => matches!(class, {members}), // {names[form_type]}')
lines += ['        _ => false,', '    }', '}', '']
open(OUT, 'w', encoding='ascii').write('\n'.join(lines))
print(len(classes), 'types,', len(used), 'classes')
