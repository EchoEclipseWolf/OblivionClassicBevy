#!/usr/bin/env python3
"""Generate tes/game_settings_table.rs from the C++ table, which came from the Phase 07 GMST extraction in IDA."""
import os
import re
SRC = os.path.join(os.environ.get('OBLIVION_CPP_DIR', '../OblivionRecomp'), 'src/tes/game_settings_table.inc')
OUT = 'crates/recomp_game/src/tes/game_settings_table.rs'
ROW = re.compile(r'^\{(\d+), (0x[0-9A-F]+)U, (0x[0-9A-F]+)U, \'(.)\', ("(?:[^"\\]|\\.)*"|nullptr), (0x[0-9A-F]+)U, ("(?:[^"\\]|\\.)*"|nullptr)\},$')
def opt(token):
    return 'None' if token == 'nullptr' else f'Some({token})'
def opt_bytes(token):
    # The C++ table writes non-ASCII bytes as octal escapes, which Rust doesn't have.
    token = re.sub(r'\\([0-7]{3})', lambda m: '\\x%02x' % int(m.group(1), 8), token)
    return 'None' if token == 'nullptr' else f'Some(b{token})'
rows = []
for line in open(SRC, encoding='ascii'):
    if line.startswith('{'):
        m = ROW.match(line.rstrip())
        if not m:
            raise SystemExit('unparsed row: ' + line)
        slot, site, address, kind, name, raw, text = m.groups()
        rows.append(f"    d({slot}, {site}, {address}, b'{kind}', {opt(name)}, {raw}, {opt_bytes(text)}),")
assert len(rows) == 2304, len(rows)
out = ['//! IDA: every 00419A70 SettingValue32_ctor and 0041BAE0 FloatSetting_ctor call in CRT initializer order (cinit slot, then',
       '//! call address). Generated by tools/game_settings_table/generate.py from the C++ table. Do not edit.', '',
       'use super::game_settings::GameSettingDefinition;', '',
       'const fn d(slot: u32, call_site: u32, address: u32, kind: u8, name: Option<&\'static str>, raw: u32, text: Option<&\'static [u8]>) -> GameSettingDefinition {',
       '    GameSettingDefinition { slot, call_site, address, kind, name, raw, text }', '}', '',
       '#[rustfmt::skip]', 'pub const GAME_SETTING_DEFINITIONS: &[GameSettingDefinition] = &['] + rows + ['];', '']
open(OUT, 'w', encoding='ascii').write('\n'.join(out))
