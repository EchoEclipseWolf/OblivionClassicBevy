#!/usr/bin/env python3
"""Generate crates/oblivion_sim/src/tes/ai/condition_tables.rs from the evidence binary's .data bytes.

00B0C8C0 is the condition function table, 0x171 rows of 0x28 bytes: +0x00 the name, +0x10 byte requires a subject,
+0x12 u16 parameter count, +0x14 the 12-byte parameter infos (+0x04 the kind), +0x20 the handler.
00B0A548 is the 8-byte parameter kinds: +0x00 the kind, +0x05 byte a form parameter.
The C++ port's two .inc files are checked against the same bytes, and a difference stops the run. Run from the
repository root.
"""
import re
import struct

EXE = '/run/media/natfoth/Echo/OblivionBot/Oblivion.exe'
OUT = 'crates/oblivion_sim/src/tes/ai/condition_tables.rs'
CPP_FUNCTIONS = '/run/media/natfoth/Echo/OblivionRecomp/src/tes/condition_functions.inc'
CPP_DISPATCH = '/run/media/natfoth/Echo/OblivionRecomp/src/tes/condition_dispatch.inc'
FUNCTIONS = 0x00B0C8C0
KINDS = 0x00B0A548
PROCEDURE_ROWS = 0x00B152B0
PROCEDURE_BLOCK = 0x00B150D4
PROCEDURE_END = 0x00B15350
FUNCTION_COUNT = 0x171

data = open(EXE, 'rb').read()
pe = struct.unpack_from('<I', data, 0x3C)[0]
sections = struct.unpack_from('<H', data, pe + 6)[0]
optional = struct.unpack_from('<H', data, pe + 20)[0]
base = struct.unpack_from('<I', data, pe + 52)[0]
table = []
for index in range(sections):
    at = pe + 24 + optional + 40 * index
    virtual_size, virtual_address, raw_size, raw_offset = struct.unpack_from('<IIII', data, at + 8)
    table.append((virtual_address + base, max(virtual_size, raw_size), raw_offset))


def offset(va):
    for start, size, raw in table:
        if start <= va < start + size:
            return raw + va - start
    raise ValueError(hex(va))


def dword(va):
    return struct.unpack_from('<I', data, offset(va))[0]


def word(va):
    return struct.unpack_from('<H', data, offset(va))[0]


def byte(va):
    return data[offset(va)]


def text(va):
    at = offset(va)
    return data[at:data.index(b'\0', at)].decode('ascii')


rows = []
for index in range(FUNCTION_COUNT):
    at = FUNCTIONS + index * 0x28
    name = text(dword(at))
    subject = byte(at + 0x10)
    count = word(at + 0x12)
    infos = dword(at + 0x14)
    kinds = [dword(infos + 12 * parameter + 4) for parameter in range(count)] if infos else []
    handler = dword(at + 0x20)
    rows.append((index, name, handler, subject, count, kinds))

kind_count = max((kind for row in rows for kind in row[5]), default=0) + 1
kinds = []
for index in range(kind_count):
    at = KINDS + 8 * index
    kinds.append((dword(at), byte(at + 5)))

# The C++ tables, row by row.
pattern = re.compile(r'\{0x([0-9A-F]+)U, (\d+), \{([^}]*)\}\}, // ([0-9A-F]{3}) (\S*)')
differences = []
for line in open(CPP_FUNCTIONS, encoding='ascii'):
    match = pattern.search(line)
    if not match:
        continue
    handler, count, listed, index, name = match.groups()
    row = rows[int(index, 16)]
    listed = [int(item.strip()[2:-1], 16) for item in listed.split(',')]
    expected = row[5][:3] + [0xFFFFFFFF] * (3 - min(3, len(row[5])))
    if int(handler, 16) != row[2] or int(count) != row[4] or listed != expected or name != row[1]:
        differences.append((index, line.strip(), row))
pattern = re.compile(r'\{0x([0-9A-F]+)U, (\d+), (\d+), \{([^}]*)\}\}, // ([0-9A-F]{3}) (\S*)')
for line in open(CPP_DISPATCH, encoding='ascii'):
    match = pattern.search(line)
    if not match:
        continue
    handler, subject, count, listed, index, name = match.groups()
    row = rows[int(index, 16)]
    if int(handler, 16) != row[2] or int(subject) != row[3] or int(count) != row[4] or name != row[1]:
        differences.append((index, line.strip(), row))
if differences:
    raise SystemExit('the C++ tables differ from the exe: %r' % differences[:10])

out = [
    "//! IDA: 00B0C8C0, the condition function table, and 00B0A548, the parameter kinds, as bytes of the evidence binary. Generated by tools/condition_tables/generate.py, which checks both of the C++ port's tables against the same bytes. Do not edit.",
    '',
    '/// IDA: a 0x28-byte row of 00B0C8C0.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct ConditionFunction {',
    '    /// +0x00.',
    "    pub name: &'static str,",
    '    /// +0x10.',
    '    pub requires_subject_10: u8,',
    '    /// +0x12.',
    '    pub parameter_count_12: u16,',
    '    /// +0x14: each 12-byte info\'s +0x04.',
    "    pub parameter_kinds_14: &'static [u32],",
    '    /// +0x20: 0 for a function that is no condition function.',
    '    pub handler_20: u32,',
    '}',
    '',
    '/// IDA: an 8-byte row of 00B0A548.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct ConditionParameterKind {',
    '    /// +0x00.',
    '    pub kind_00: u32,',
    '    /// +0x05: the parameter holds a form ID.',
    '    pub is_form_05: u8,',
    '}',
    '',
    'const fn f(',
    "    name: &'static str,",
    '    requires_subject_10: u8,',
    '    parameter_count_12: u16,',
    "    parameter_kinds_14: &'static [u32],",
    '    handler_20: u32,',
    ') -> ConditionFunction {',
    '    ConditionFunction {',
    '        name,',
    '        requires_subject_10,',
    '        parameter_count_12,',
    '        parameter_kinds_14,',
    '        handler_20,',
    '    }',
    '}',
    '',
    '#[rustfmt::skip]',
    f'pub const CONDITION_FUNCTIONS: [ConditionFunction; 0x{FUNCTION_COUNT:X}] = [',
]
for index, name, handler, subject, count, row_kinds in rows:
    listed = ', '.join(f'0x{kind:X}' for kind in row_kinds)
    out.append(f'    f("{name}", {subject}, {count}, &[{listed}], 0x{handler:08X}), // {index:03X}')
out += ['];', '', '#[rustfmt::skip]', f'pub const CONDITION_PARAMETER_KINDS: [ConditionParameterKind; {kind_count}] = [']
for kind, is_form in kinds:
    out.append(f'    ConditionParameterKind {{ kind_00: 0x{kind:X}, is_form_05: {is_form} }},')
out += ['];', '']
# 00B152B0: 40 row pointers into a flat dword block. A row is read past its 0x2C end by whatever follows it in memory, so the block stays whole, with the row table itself behind it.
words = [dword(va) for va in range(PROCEDURE_BLOCK, PROCEDURE_END, 4)]
row_starts = [(dword(PROCEDURE_ROWS + 4 * row) - PROCEDURE_BLOCK) // 4 for row in range(40)]
out += [
    '/// IDA: 00B150D4..00B15350, the dwords the 00B152B0 rows point into, then the row table itself.',
    '#[rustfmt::skip]',
    f'pub const PROCEDURE_BLOCK: [u32; {len(words)}] = [',
    '    ' + ', '.join(f'0x{word:X}' for word in words) + ',',
    '];',
    '',
    '/// IDA: 00B152B0, each row as an index into `PROCEDURE_BLOCK`.',
    '#[rustfmt::skip]',
    f'pub const PROCEDURE_ROWS: [u16; {len(row_starts)}] = [',
    '    ' + ', '.join(str(row) for row in row_starts) + ',',
    '];',
    '',
]
open(OUT, 'w', encoding='ascii').write('\n'.join(out))
print(len(rows), 'functions,', kind_count, 'kinds, the C++ tables agree')
